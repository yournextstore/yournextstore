"use client";

import { Search } from "lucide-react";
import { useId, useRef, useState } from "react";
import { Suggestions } from "@/components/search/suggestions";
import {
	getActiveId,
	makeKeyHandler,
	makeNavHandlers,
	useSearchController,
} from "@/components/search/use-search-controller";

export function SearchPageInput({ initialQuery }: { initialQuery: string }) {
	const c = useSearchController(initialQuery);
	const [interactive, setInteractive] = useState(false);
	const inputRef = useRef<HTMLInputElement>(null);
	const listboxId = useId();

	const close = () => {
		setInteractive(false);
		inputRef.current?.blur();
	};
	const { goToSearch, goToProduct, handleSubmit } = makeNavHandlers(c, close);

	const panelOpen = interactive && c.enoughChars;

	return (
		<search>
			<form onSubmit={handleSubmit}>
				<label htmlFor={`${listboxId}-input`} className="sr-only">
					Search products
				</label>
				<div className="relative rounded-xl bg-flash-white focus-within:ring-2 focus-within:ring-green-500">
					<Search
						className="pointer-events-none absolute right-5 top-1/2 h-6 w-6 -translate-y-1/2 text-foreground"
						strokeWidth={1.5}
					/>
					<input
						ref={inputRef}
						id={`${listboxId}-input`}
						type="search"
						name="q"
						placeholder="Search the store"
						value={c.query}
						onFocus={() => setInteractive(true)}
						onBlur={() => setTimeout(() => setInteractive(false), 120)}
						onChange={(e) => {
							setInteractive(true);
							c.setQuery(e.target.value);
						}}
						onKeyDown={makeKeyHandler(c, panelOpen, close, () => goToSearch(c.query))}
						role="combobox"
						aria-expanded={panelOpen}
						aria-controls={listboxId}
						aria-autocomplete="list"
						aria-activedescendant={getActiveId(listboxId, c, panelOpen)}
						enterKeyHint="search"
						autoComplete="off"
						className="h-16 w-full border-0 bg-transparent pl-5 pr-14 text-gf-h5 text-foreground placeholder:text-foreground focus:outline-none [&::-webkit-search-cancel-button]:hidden"
					/>
				</div>
				{panelOpen ? (
					<div className="mt-3 rounded-xl bg-white p-1 gf-shadow">
						<Suggestions
							listboxId={listboxId}
							open={panelOpen}
							c={c}
							onPick={goToProduct}
							onSeeAll={() => goToSearch(c.query)}
						/>
					</div>
				) : null}
			</form>
		</search>
	);
}
